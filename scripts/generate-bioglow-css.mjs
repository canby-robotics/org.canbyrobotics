import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDirectory = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const tokenPath = path.join(
  rootDirectory,
  "src",
  "brand",
  "bioglow.tokens.json",
);
const cssPath = path.join(rootDirectory, "src", "brand", "bioglow.css");

const expectedCoreTokens = [
  "black",
  "dark-green",
  "green",
  "light-green",
  "yellow",
];
const expectedEditions = ["founders", "future"];
const expectedEditionStatuses = {
  founders: "active",
  future: "reference-only",
};

function assert(condition, message) {
  if (!condition) {
    throw new Error(message);
  }
}

function arraysMatch(left, right) {
  return (
    left.length === right.length &&
    left.every((value, index) => value === right[index])
  );
}

function hexFromRgb(rgb) {
  return `#${rgb
    .map((channel) => channel.toString(16).padStart(2, "0"))
    .join("")
    .toUpperCase()}`;
}

function validateColor(
  id,
  color,
  seenVariables,
  seenHexValues,
  requiresCssVariable = true,
) {
  if (requiresCssVariable) {
    assert(
      /^--bioglow-[a-z0-9-]+$/.test(color.cssVariable),
      `${id} has an invalid CSS variable name`,
    );
  } else {
    assert(
      color.cssVariable === undefined,
      `${id} is reference-only and must not expose a CSS variable`,
    );
  }
  assert(
    /^#[0-9A-F]{6}$/.test(color.hex),
    `${id} must use an uppercase six-digit HEX value`,
  );
  assert(
    Array.isArray(color.rgb) &&
      color.rgb.length === 3 &&
      color.rgb.every(
        (channel) =>
          Number.isInteger(channel) && channel >= 0 && channel <= 255,
      ),
    `${id} must define three integer RGB channels`,
  );
  assert(
    hexFromRgb(color.rgb) === color.hex,
    `${id} has mismatched HEX and RGB values`,
  );
  assert(
    Array.isArray(color.cmyk) &&
      color.cmyk.length === 4 &&
      color.cmyk.every(
        (channel) =>
          Number.isInteger(channel) && channel >= 0 && channel <= 100,
      ),
    `${id} must define four integer CMYK channels`,
  );
  assert(
    typeof color.label === "string" && color.label.length > 0,
    `${id} must define a label`,
  );
  assert(
    typeof color.pms === "string" && color.pms.length > 0,
    `${id} must define a PMS value`,
  );
  if (requiresCssVariable) {
    assert(
      !seenVariables.has(color.cssVariable),
      `${id} duplicates the CSS variable ${color.cssVariable}`,
    );
  }
  assert(
    !seenHexValues.has(color.hex),
    `${id} duplicates the HEX value ${color.hex}`,
  );

  if (requiresCssVariable) {
    seenVariables.add(color.cssVariable);
  }
  seenHexValues.add(color.hex);
}

function validateTokens(tokens) {
  assert(tokens.name === "BIOGLOW", "The token set name must be BIOGLOW");
  assert(
    tokens.season === "2026-2027",
    "The token set season must be 2026-2027",
  );
  assert(
    tokens.source?.reference === "FL078",
    "The token set must identify source reference FL078",
  );
  assert(
    tokens.project?.activeEdition === "founders",
    "The project active edition must be founders",
  );

  const coreTokens = Object.keys(tokens.colors?.core ?? {}).sort();
  const editions = Object.keys(tokens.colors?.editions ?? {}).sort();

  assert(
    arraysMatch(coreTokens, expectedCoreTokens),
    `Core tokens must be: ${expectedCoreTokens.join(", ")}`,
  );
  assert(
    arraysMatch(editions, expectedEditions),
    `Edition tokens must be: ${expectedEditions.join(", ")}`,
  );

  const seenVariables = new Set();
  const seenHexValues = new Set();

  for (const [id, color] of Object.entries(tokens.colors.core)) {
    validateColor(`core.${id}`, color, seenVariables, seenHexValues);
  }

  for (const [id, color] of Object.entries(tokens.colors.editions)) {
    const expectedStatus = expectedEditionStatuses[id];
    assert(
      color.projectStatus === expectedStatus,
      `editions.${id} must have projectStatus ${expectedStatus}`,
    );
    validateColor(
      `editions.${id}`,
      color,
      seenVariables,
      seenHexValues,
      color.projectStatus === "active",
    );
  }
}

function generateCss(tokens) {
  const activeEditions = Object.entries(tokens.colors.editions).filter(
    ([, color]) => color.projectStatus === "active",
  );
  assert(
    activeEditions.length === 1 &&
      activeEditions[0][0] === tokens.project.activeEdition,
    "Exactly one edition must be active",
  );

  const colors = [
    ...Object.values(tokens.colors.core),
    ...activeEditions.map(([, color]) => color),
  ].sort((left, right) => left.cssVariable.localeCompare(right.cssVariable));

  const lines = [
    "/* Generated by scripts/generate-bioglow-css.mjs. Do not edit directly. */",
    "",
    ":root {",
    ...colors.map(
      (color) => `  ${color.cssVariable}: ${color.hex};`,
    ),
    "}",
    "",
  ];

  for (const [edition, color] of activeEditions) {
    lines.push(
      `[data-bioglow-edition="${edition}"] {`,
      `  --bioglow-edition-accent: var(${color.cssVariable});`,
      "}",
      "",
    );
  }

  return `${lines.join("\n")}\n`;
}

async function main() {
  const mode = process.argv[2];
  assert(
    mode === "--write" || mode === "--check",
    "Usage: node scripts/generate-bioglow-css.mjs --write|--check",
  );

  const tokens = JSON.parse(await readFile(tokenPath, "utf8"));
  validateTokens(tokens);
  const generatedCss = generateCss(tokens);

  if (mode === "--write") {
    await writeFile(cssPath, generatedCss);
    console.log("Generated src/brand/bioglow.css");
    return;
  }

  let currentCss;
  try {
    currentCss = await readFile(cssPath, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") {
      throw error;
    }
  }

  assert(
    currentCss === generatedCss,
    "BIOGLOW CSS is stale. Run npm run brand:generate and commit the result.",
  );
  console.log("BIOGLOW tokens are valid and generated CSS is current.");
}

main().catch((error) => {
  console.error(error.message);
  process.exitCode = 1;
});
